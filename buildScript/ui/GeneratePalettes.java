// Run with JDK 17 and classes.jar extracted from the pinned Material 1.12.0 AAR:
// java -cp /path/to/classes.jar buildScript/ui/GeneratePalettes.java app/src/main/res
import com.google.android.material.color.utilities.*;
import java.nio.file.*;
import java.util.*;

class GeneratePalettes {
    public static void main(String[] args) throws Exception {
        String[] names = {"Red","Pink_SSR","Pink","Purple","DeepPurple","Indigo","Blue","LightBlue","Cyan","Teal","Green","LightGreen","Lime","Yellow","Amber","Orange","DeepOrange","Brown","Grey","BlueGrey","Black"};
        int[] seeds = {0xffe53935,0xffe91e63,0xfff06292,0xff9c27b0,0xff673ab7,0xff3f51b5,0xff2196f3,0xff03a9f4,0xff00bcd4,0xff009688,0xff4caf50,0xff8bc34a,0xffcddc39,0xffffeb3b,0xffffc107,0xffff9800,0xffff5722,0xff795548,0xff9e9e9e,0xff607d8b,0xff303030};
        String[] roles = {"primary","onPrimary","primaryContainer","onPrimaryContainer","secondary","onSecondary","secondaryContainer","onSecondaryContainer","tertiary","onTertiary","tertiaryContainer","onTertiaryContainer","surface","onSurface","surfaceVariant","onSurfaceVariant","surfaceContainer","surfaceContainerLow","surfaceContainerHigh","surfaceContainerHighest","outline","outlineVariant","error","onError","errorContainer","onErrorContainer"};
        MaterialDynamicColors colors = new MaterialDynamicColors();
        for (boolean dark : new boolean[]{false,true}) {
            StringBuilder xml = new StringBuilder("<?xml version=\"1.0\" encoding=\"utf-8\"?>\n<!-- Generated by buildScript/ui/GeneratePalettes.java with Material 1.12.0. -->\n<resources>\n");
            for (int i=0;i<names.length;i++) {
                DynamicScheme scheme = new SchemeTonalSpot(Hct.fromInt(seeds[i]),dark,0);
                for (String role:roles) {
                    DynamicColor color = (DynamicColor)MaterialDynamicColors.class.getMethod(role).invoke(colors);
                    xml.append(String.format(Locale.ROOT,"    <color name=\"thbox_%s_%s\">#%08X</color>\n",names[i].toLowerCase(Locale.ROOT),role.toLowerCase(Locale.ROOT),color.getArgb(scheme)));
                }
            }
            xml.append("</resources>\n");
            Path path=Path.of(args[0],dark?"values-night":"values","m3-palettes.xml");
            Files.createDirectories(path.getParent()); Files.writeString(path,xml);
        }
    }
}
